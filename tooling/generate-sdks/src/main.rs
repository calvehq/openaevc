//! `cargo run -p generate-sdks [-- --check]`
//!
//! Generates, from the protocol schema and type tables:
//! * `sdk/typescript/src/generated.ts` — TypeScript types for every schema definition + constants;
//! * `sdk/python/openaevc/_generated.py` — protocol constants;
//! * `sdk/go/generated.go` — protocol constants.
//! The handwritten SDK layers build on these. With `--check`, fails on any difference.

use generate_schemas::{json_schema, root};
use openaevc_protocol::{
    Command, ErrorCode, ObjectKind, Query, CONTRACT_VERSION, PROTOCOL_VERSION,
};
use serde_json::Value;

const HEADER: &str =
    "Generated by tooling/generate-sdks from the OpenAEVC protocol schema. Do not edit.";

fn ts_name(r: &str) -> String {
    r.rsplit('/').next().unwrap_or("unknown").to_owned()
}

fn ts_type(v: &Value) -> String {
    if let Some(r) = v.get("$ref").and_then(Value::as_str) {
        return ts_name(r);
    }
    for key in ["oneOf", "anyOf"] {
        if let Some(alts) = v.get(key).and_then(Value::as_array) {
            let parts: Vec<String> = alts
                .iter()
                .filter(|a| a.get("type").and_then(Value::as_str) != Some("null"))
                .map(ts_type)
                .collect();
            return if parts.len() == 1 {
                parts[0].clone()
            } else {
                format!("({})", parts.join(" | "))
            };
        }
    }
    if let Some(c) = v.get("const") {
        return c.to_string();
    }
    if let Some(e) = v.get("enum").and_then(Value::as_array) {
        return e
            .iter()
            .map(|x| x.to_string())
            .collect::<Vec<_>>()
            .join(" | ");
    }
    let ty = match v.get("type") {
        Some(Value::Array(ts)) => ts
            .iter()
            .find(|t| *t != "null")
            .and_then(Value::as_str)
            .unwrap_or("unknown"),
        Some(Value::String(t)) => t.as_str(),
        _ => return "unknown".into(),
    };
    match ty {
        "string" => "string".into(),
        "integer" | "number" => "number".into(),
        "boolean" => "boolean".into(),
        "array" => format!(
            "Array<{}>",
            v.get("items")
                .map(ts_type)
                .unwrap_or_else(|| "unknown".into())
        ),
        "object" => ts_object(v),
        _ => "unknown".into(),
    }
}

fn ts_object(v: &Value) -> String {
    let required: Vec<&str> = v
        .get("required")
        .and_then(Value::as_array)
        .map(|r| r.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let mut fields = Vec::new();
    if let Some(props) = v.get("properties").and_then(Value::as_object) {
        for (k, pv) in props {
            let opt = if required.contains(&k.as_str()) {
                ""
            } else {
                "?"
            };
            fields.push(format!("{k}{opt}: {}", ts_type(pv)));
        }
    }
    match v.get("additionalProperties") {
        Some(ap @ Value::Object(_)) => fields.push(format!("[key: string]: {}", ts_type(ap))),
        Some(Value::Bool(false)) => {}
        _ if fields.is_empty() => fields.push("[key: string]: unknown".into()),
        _ => {}
    }
    format!("{{ {} }}", fields.join("; "))
}

fn list<T>(items: &[T], f: impl Fn(&T) -> String) -> Vec<String> {
    items.iter().map(f).collect()
}

struct Constants {
    commands: Vec<String>,
    queries: Vec<String>,
    errors: Vec<String>,
    kinds: Vec<String>,
    prefixes: Vec<String>,
}

fn constants() -> Constants {
    Constants {
        commands: list(Command::NAMES, |s| s.to_string()),
        queries: list(Query::NAMES, |s| s.to_string()),
        errors: list(ErrorCode::ALL, |c| c.as_str().to_string()),
        kinds: list(ObjectKind::ALL, |k| k.as_str().to_string()),
        prefixes: [
            "ns", "pri", "grt", "cpk", "rpk", "exe", "obs", "evd", "vrf", "evl", "pro", "bsl",
            "evt", "wku", "lse", "req", "eff", "rti",
        ]
        .iter()
        .map(|s| s.to_string())
        .collect(),
    }
}

fn quoted(v: &[String]) -> String {
    v.iter()
        .map(|s| format!("\"{s}\""))
        .collect::<Vec<_>>()
        .join(", ")
}

fn typescript(schema: &Value, c: &Constants) -> String {
    let mut out = format!("// {HEADER}\n/* eslint-disable */\n\n");
    out.push_str(&format!("export const PROTOCOL_VERSION = \"{PROTOCOL_VERSION}\";\nexport const CONTRACT_VERSION = \"{CONTRACT_VERSION}\";\n"));
    out.push_str(&format!(
        "export const COMMANDS = [{}] as const;\n",
        quoted(&c.commands)
    ));
    out.push_str(&format!(
        "export const QUERIES = [{}] as const;\n",
        quoted(&c.queries)
    ));
    out.push_str(&format!(
        "export const ERROR_CODES = [{}] as const;\n",
        quoted(&c.errors)
    ));
    out.push_str(&format!(
        "export const OBJECT_KINDS = [{}] as const;\n",
        quoted(&c.kinds)
    ));
    out.push_str(&format!(
        "export const ID_PREFIXES = [{}] as const;\n\n",
        quoted(&c.prefixes)
    ));
    for (name, def) in schema["$defs"].as_object().into_iter().flatten() {
        if let Some(d) = def.get("description").and_then(Value::as_str) {
            out.push_str(&format!(
                "/** {} */\n",
                d.replace("*/", "*\\/").replace('\n', " ")
            ));
        }
        out.push_str(&format!("export type {name} = {};\n", ts_type(def)));
    }
    out
}

fn python(c: &Constants) -> String {
    format!(
        "# {HEADER}\n\"\"\"Protocol constants.\"\"\"\n\nPROTOCOL_VERSION = \"{PROTOCOL_VERSION}\"\nCONTRACT_VERSION = \"{CONTRACT_VERSION}\"\nCOMMANDS = ({},)\nQUERIES = ({},)\nERROR_CODES = ({},)\nOBJECT_KINDS = ({},)\nID_PREFIXES = ({},)\n",
        quoted(&c.commands),
        quoted(&c.queries),
        quoted(&c.errors),
        quoted(&c.kinds),
        quoted(&c.prefixes)
    )
}

fn go(c: &Constants) -> String {
    let block = |name: &str, v: &[String]| format!("var {name} = []string{{{}}}\n\n", quoted(v));
    let mut out = format!("// {HEADER}\n\npackage openaevc\n\n// ProtocolVersion is the protocol version implemented by this SDK.\nconst ProtocolVersion = \"{PROTOCOL_VERSION}\"\n\n// ContractVersion is the extension contract version.\nconst ContractVersion = \"{CONTRACT_VERSION}\"\n\n");
    out.push_str("// Commands lists every command type.\n");
    out.push_str(&block("Commands", &c.commands));
    out.push_str("// Queries lists every query type.\n");
    out.push_str(&block("Queries", &c.queries));
    out.push_str("// ErrorCodes lists every protocol error code.\n");
    out.push_str(&block("ErrorCodes", &c.errors));
    out.push_str("// ObjectKinds lists every immutable object kind.\n");
    out.push_str(&block("ObjectKinds", &c.kinds));
    out.push_str("// IDPrefixes lists every typed identifier prefix.\n");
    out.push_str(block("IDPrefixes", &c.prefixes).trim_end());
    out.push('\n');
    out
}

fn main() {
    let check = std::env::args().any(|a| a == "--check");
    let schema = json_schema();
    let c = constants();
    let files = [
        ("sdk/typescript/src/generated.ts", typescript(&schema, &c)),
        ("sdk/python/openaevc/_generated.py", python(&c)),
        ("sdk/go/generated.go", go(&c)),
    ];
    let mut stale = false;
    for (rel, content) in files {
        let path = root().join(rel);
        if check {
            if std::fs::read_to_string(&path).ok().as_deref() != Some(content.as_str()) {
                eprintln!("{rel} is out of date; run `cargo run -p generate-sdks`");
                stale = true;
            }
        } else {
            std::fs::write(&path, content).unwrap_or_else(|e| panic!("writing {rel}: {e}"));
            println!("wrote {rel}");
        }
    }
    if stale {
        std::process::exit(1);
    }
}
